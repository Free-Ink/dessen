// Turns the C-side single sources into what the Rust crate needs, so nothing is
// written down twice:
//   sdk/dessen_abi.h -> $OUT_DIR/abi.rs   (every `#define DSN_*` constant)
//   sdk/app.ld       -> $OUT_DIR/dessen.ld (the link script, on the search path)
// The call wrappers come from sdk/dessen.rs, which tools/gen_api.py generates.
use std::{env, fs, path::PathBuf};

fn main() {
    let sdk = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("..");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    let header = sdk.join("dessen_abi.h");
    let text = fs::read_to_string(&header).expect("sdk/dessen_abi.h");
    let mut abi =
        String::from("// Generated by sdk/rust/build.rs from sdk/dessen_abi.h. Do not edit.\n");
    for line in text.lines() {
        if let Some(rust) = constant(line) {
            abi.push_str(&rust);
            abi.push('\n');
        }
    }
    fs::write(out.join("abi.rs"), abi).unwrap();

    // An app links with `-C link-arg=-Tdessen.ld`; this puts the script on the
    // search path of every crate that depends on this one. This crate's own
    // examples get the flag directly.
    fs::copy(sdk.join("app.ld"), out.join("dessen.ld")).unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    if env::var("CARGO_FEATURE_RT").is_ok() {
        println!("cargo:rustc-link-arg-examples=-Tdessen.ld");
    }

    println!("cargo:rerun-if-changed={}", header.display());
    println!("cargo:rerun-if-changed={}", sdk.join("app.ld").display());
    println!("cargo:rerun-if-changed={}", sdk.join("dessen.rs").display());
}

// `#define DSN_NAME <value>` -> `pub const DSN_NAME: <ty> = <value>;`.
// Values are integer literals (`0x314e5344u` -> u32), parenthesised negatives,
// or arithmetic over earlier constants. Function-like macros and anything else
// are skipped: they are helpers, not ABI values.
fn constant(line: &str) -> Option<String> {
    let rest = line.trim().strip_prefix("#define ")?;
    let (name, value) = rest.split_once(char::is_whitespace)?;
    if !name.starts_with("DSN_") || name.contains('(') {
        return None;
    }
    let value = value.split("//").next()?.trim();
    if value.is_empty() {
        return None;
    }
    if let Some(hex) = value.strip_suffix('u') {
        let ok = hex.starts_with("0x") && hex[2..].chars().all(|digit| digit.is_ascii_hexdigit());
        return ok.then(|| format!("pub const {name}: u32 = {hex};"));
    }
    let expr = value
        .chars()
        .all(|symbol| symbol.is_ascii_alphanumeric() || " _+-*()".contains(symbol));
    expr.then(|| format!("pub const {name}: i32 = {value};"))
}
