#!/usr/bin/env python3
"""Draw the readstats launcher glyphs and write apps/readstats_icons.rs.

Original artwork: each glyph is a few primitives on a 48x48 grid, drawn 4x
oversized, thresholded to 1 bit and knocked out of a black rounded-square tile.
The app blits a whole tile as one black/white bitmap (MSB first, set bit =
black, rows padded to a byte). Re-run after editing:
    python3 tools/readstats_icons.py [preview.png]
"""
import os, sys
from PIL import Image, ImageDraw

N, S, T, R = 48, 4, 84, 20  # glyph size, oversampling, tile size, tile corner radius


def glyph(paint):
    im = Image.new("L", (N * S, N * S), 0)
    d = ImageDraw.Draw(im)
    k = lambda *v: [x * S for x in v]
    paint(d, k)
    return im.resize((N, N), Image.LANCZOS).point(lambda v: 255 if v >= 128 else 0).convert("1")


def library(d, k):  # books on a shelf, one leaning
    d.rounded_rectangle(k(7, 11, 15, 37), 2 * S, fill=255)
    d.rounded_rectangle(k(18, 6, 26, 37), 2 * S, fill=255)
    d.polygon(k(29, 13, 35, 11, 42, 35, 36, 37), fill=255)
    d.rounded_rectangle(k(5, 39, 43, 43), S, fill=255)


def files(d, k):  # folder with a tab
    d.rounded_rectangle(k(5, 9, 23, 22), 3 * S, fill=255)
    d.rounded_rectangle(k(5, 15, 43, 39), 4 * S, fill=255)
    d.rectangle(k(10, 21, 38, 23), fill=0)


def catalog(d, k):  # globe: online catalogs
    d.ellipse(k(5, 5, 43, 43), outline=255, width=3 * S)
    d.ellipse(k(16, 5, 32, 43), outline=255, width=3 * S)
    d.rectangle(k(6, 22.5, 42, 25.5), fill=255)


def apps(d, k):  # three tiles and a dot
    for x, y in ((7, 7), (27, 7), (7, 27)):
        d.rounded_rectangle(k(x, y, x + 14, y + 14), 3 * S, fill=255)
    d.ellipse(k(26, 26, 42, 42), fill=255)


def transfer(d, k):  # up and down arrows
    d.rectangle(k(13, 16, 19, 41), fill=255)
    d.polygon(k(5, 19, 16, 6, 27, 19), fill=255)
    d.rectangle(k(29, 7, 35, 32), fill=255)
    d.polygon(k(21, 29, 32, 42, 43, 29), fill=255)


def settings(d, k):  # sliders
    for y, x in ((11, 30), (24, 15), (37, 33)):
        d.rounded_rectangle(k(6, y - 1.5, 42, y + 1.5), S, fill=255)
        d.ellipse(k(x - 6, y - 6, x + 6, y + 6), fill=0)
        d.ellipse(k(x - 4.5, y - 4.5, x + 4.5, y + 4.5), fill=255)


ICONS = [library, files, catalog, apps, transfer, settings]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def tile(g):
    big = Image.new("L", (T * S, T * S), 0)
    ImageDraw.Draw(big).rounded_rectangle([0, 0, T * S - 1, T * S - 1], R * S, fill=255)
    im = big.resize((T, T), Image.LANCZOS).point(lambda v: 255 if v >= 128 else 0).convert("1")
    im.paste(0, ((T - N) // 2, (T - N) // 2), g)
    return im


tiles = [tile(glyph(f)) for f in ICONS]
with open(os.path.join(root, "apps", "readstats_icons.rs"), "w") as f:
    f.write("// Generated by tools/readstats_icons.py. Do not edit.\n")
    f.write("// Launcher icons: %dx%d, 1 bit, MSB first, set bit = black, rows padded to a byte.\n" % (T, T))
    f.write("const TILE: i32 = %d;\n" % T)
    f.write("const TILES: [[u8; %d]; %d] = [\n" % ((T + 7) // 8 * T, len(ICONS)))
    for fn, im in zip(ICONS, tiles):
        f.write("    [%s], // %s\n" % (", ".join("0x%02x" % b for b in im.tobytes()), fn.__name__))
    f.write("];\n")

if len(sys.argv) > 1:  # contact sheet
    G = 16
    sheet = Image.new("L", (len(ICONS) * (T + G) + G, T + 2 * G), 255)
    for i, im in enumerate(tiles):
        sheet.paste(0, (G + i * (T + G), G), im)
    sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(sys.argv[1])
