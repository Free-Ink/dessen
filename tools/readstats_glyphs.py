#!/usr/bin/env python3
"""Cut the readstats launcher glyphs out of apps/readstats_icons.rs and write
apps/xpui/readstats/src/glyphs.rs.

apps/readstats_icons.rs (from tools/readstats_icons.py) holds each icon as a
whole 84x84 tile: a black rounded square with a 48x48 glyph knocked out of its
middle. The xpui app paints the square itself (dsn_fill_round) and draws only
the glyph over it in white, so it carries 288 bytes an icon instead of 924.
Here a set bit is the glyph, rows MSB first and padded to a byte. Re-run after
regenerating the icons:
    python3 tools/readstats_glyphs.py
"""
import os, re

T, N, R = 84, 48, 20  # tile, glyph and corner radius, as tools/readstats_icons.py draws them
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "apps", "readstats_icons.rs")).read()
rows = re.findall(r"\[([0-9a-fx, ]+)\], // (\w+)", src)
stride, off = (T + 7) // 8, (T - N) // 2


def bit(data, x, y):
    return (data[y * stride + x // 8] >> (7 - x % 8)) & 1


out = []
for hexes, name in rows:
    data = [int(h, 16) for h in hexes.split(", ")]
    assert len(data) == stride * T, name
    glyph = bytearray()
    for y in range(N):
        for xb in range(0, N, 8):
            byte = 0
            for x in range(xb, xb + 8):
                # Inside the tile a clear bit is the knocked-out glyph.
                byte = byte << 1 | (1 - bit(data, off + x, off + y))
            glyph.append(byte)
    out.append((name, glyph))

with open(os.path.join(root, "apps", "xpui", "readstats", "src", "glyphs.rs"), "w") as f:
    f.write("// Generated by tools/readstats_glyphs.py from apps/readstats_icons.rs. Do not edit.\n")
    f.write("//! The launcher glyphs: %dx%d, 1 bit, MSB first, a set bit is the glyph.\n\n" % (N, N))
    f.write("/// The rounded tile each glyph sits on, and its corner radius.\n")
    f.write("pub const TILE: i32 = %d;\npub const TILE_RADIUS: i32 = %d;\n" % (T, R))
    f.write("/// A glyph's side; it is centred on its tile.\npub const GLYPH: i32 = %d;\n" % N)
    f.write("/// The glyphs, in the order of `apps/readstats_icons.rs`.\n")
    f.write("pub const GLYPHS: [[u8; %d]; %d] = [\n" % (N // 8 * N, len(out)))
    for name, g in out:
        f.write("    [%s], // %s\n" % (", ".join("0x%02x" % b for b in g), name))
    f.write("];\n")
