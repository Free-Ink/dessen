#!/usr/bin/env python3
"""Generate the dessen app wrappers and firmware dispatch from abi/freeink.api."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BITS = {"i16": 16, "u16": 16, "u8": 8}
MAX_SLOTS = 7  # a0..a6; a7 carries the call number
# .api arg names that collide with a target language's keywords (e.g. `align`,
# `pub`, `priv`) get a trailing underscore in that language's wrappers.
RUST_KW = {"as", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn", "for",
           "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self",
           "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
           "await", "priv", "box", "final", "macro", "override", "typeof", "virtual", "yield"}
ZIG_KW = {"addrspace", "align", "allowzero", "and", "anyframe", "anytype", "asm", "async", "await", "break",
          "callconv", "catch", "comptime", "const", "continue", "defer", "else", "enum", "errdefer", "error",
          "export", "extern", "fn", "for", "if", "inline", "linksection", "noalias", "noinline", "nosuspend",
          "opaque", "or", "orelse", "packed", "pub", "resume", "return", "struct", "suspend", "switch", "test",
          "threadlocal", "try", "type", "union", "unreachable", "usingnamespace", "var", "volatile", "while"}
LINE = re.compile(r"^(\d+)\s+(\w+)\((.*?)\)\s*(?:->\s*(\w+))?\s*:\s*(.+)$")
NOTE = "// Generated by tools/gen_api.py from abi/freeink.api. Do not edit.\n"


def parse(text):
    calls, seen = [], {}
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"freeink.api:{n}: cannot parse: {line}")
        num, name, args, ret, stmt = int(m[1]), m[2], m[3], m[4], m[5]
        if num in seen or name in seen.values():
            sys.exit(f"freeink.api:{n}: duplicate number or name: {num} {name}")
        seen[num] = name
        params = [tuple(a.split()) for a in args.split(",") if a.strip()]
        slots = []  # each slot: list of (type, name, shift), or one ("ptr"/"len"/word, name, 0)
        for typ, arg in params:
            if typ in BITS:
                last = slots[-1] if slots else None
                used = sum(BITS[t] for t, _, _ in last) if last and last[0][0] in BITS else 32
                if used + BITS[typ] <= 32:
                    last.append((typ, arg, used))
                else:
                    slots.append([(typ, arg, 0)])
            elif typ in ("i32", "u32"):
                slots.append([(typ, arg, 0)])
            elif typ in ("str", "buf", "out"):
                slots.append([("ptr", arg, 0)])
                slots.append([("len", arg, 0)])
            else:
                sys.exit(f"freeink.api:{n}: unknown type {typ}")
        if len(slots) > MAX_SLOTS:
            sys.exit(f"freeink.api:{n}: {name} needs {len(slots)} registers, max {MAX_SLOTS}")
        if ret not in (None, "i32", "u32"):
            sys.exit(f"freeink.api:{n}: return type must be i32 or u32")
        calls.append(dict(num=num, name=name, params=params, slots=slots, ret=ret, stmt=stmt))
    return calls


def app_headers(calls):
    nums = NOTE + "#pragma once\n"
    for c in calls:
        nums += f"#define DSN_SYS_{c['name'].upper()} {c['num']}\n"

    out = NOTE + '#pragma once\n#include "dessen_sysnums.h"\n\n'
    for k in range(MAX_SLOTS + 1):
        regs = "".join(f"  register long r{i} __asm__(\"a{i}\") = a{i};\n" for i in range(k))
        if k == 0:
            regs = '  register long r0 __asm__("a0");\n'
        ins = "".join(f', "r"(r{i})' for i in range(1, k))
        sig = "".join(f", long a{i}" for i in range(k))
        out += (f"static inline long dsn_call{k}(long n{sig}) {{\n"
                f'  register long r7 __asm__("a7") = n;\n{regs}'
                f'  __asm__ volatile("ecall" : "{"+" if k else "="}r"(r0) : "r"(r7){ins} : "memory");\n'
                "  return r0;\n}\n")
    out += "\n"
    for c in calls:
        sig = []
        for typ, arg in c["params"]:
            if typ == "str":
                sig += [f"const char *{arg}", f"int {arg}_len"]
            elif typ == "buf":
                sig += [f"const void *{arg}", f"int {arg}_len"]
            elif typ == "out":
                sig += [f"void *{arg}", f"int {arg}_len"]
            else:
                sig.append(f"{'unsigned' if typ == 'u32' else 'int'} {arg}")
        vals = []
        for slot in c["slots"]:
            typ, arg, _ = slot[0]
            if typ == "ptr":
                vals.append(f"(long){arg}")
            elif typ == "len":
                vals.append(f"{arg}_len")
            elif typ in BITS:
                parts = [f"((unsigned){a} & {hex((1 << BITS[t]) - 1)}) << {s}" if s else
                         f"((unsigned){a} & {hex((1 << BITS[t]) - 1)})" for t, a, s in slot]
                vals.append("(long)(" + " | ".join(parts) + ")")
            else:
                vals.append(f"(long){arg}")
        call = f"dsn_call{len(vals)}(DSN_SYS_{c['name'].upper()}{''.join(', ' + v for v in vals)})"
        rtype = {"i32": "int", "u32": "unsigned", None: "void"}[c["ret"]]
        body = f"return ({rtype}){call};" if c["ret"] else f"{call};"
        out += f"static inline {rtype} dsn_{c['name']}({', '.join(sig) or 'void'}) {{ {body} }}\n"
    return nums, out


def rust_module(calls):
    """App-side ecall wrappers for Rust (no_std). include!() into your app."""
    out = NOTE + "// App-side wrappers for Rust apps (no_std). `include!` this into your crate.\n\n"
    for c in calls:
        out += f"pub const DSN_SYS_{c['name'].upper()}: usize = {c['num']};\n"
    out += "\n"
    for k in range(MAX_SLOTS + 1):
        params = "".join(f", a{i}: usize" for i in range(k))
        # The inner `unsafe {}` is what edition 2024 requires (unsafe_op_in_unsafe_fn)
        # and is accepted silently by the older editions.
        out += f"#[inline]\nunsafe fn dsn_call{k}(n: usize{params}) -> i32 {{\n    let r: i32;\n"
        out += '    unsafe {\n        core::arch::asm!(\n            "ecall",\n            in("a7") n,\n'
        out += "            out(\"a0\") r,\n" if k == 0 else "            inlateout(\"a0\") a0 => r,\n"
        out += "".join(f'            in("a{i}") a{i},\n' for i in range(1, k))
        out += "            options(nostack),\n        );\n    }\n    r\n}\n"
    out += "\n"
    rn = lambda s: s + "_" if s in RUST_KW else s
    outs_by_call = [{a for t, a in c["params"] if t == "out"} for c in calls]
    for c, outs in zip(calls, outs_by_call):
        sig = []
        for typ, arg in c["params"]:
            sig.append(f"{rn(arg)}: &[u8]" if typ in ("str", "buf")
                       else f"{rn(arg)}: &mut [u8]" if typ == "out"
                       else f"{rn(arg)}: u32" if typ == "u32" else f"{rn(arg)}: i32")
        vals = []
        for slot in c["slots"]:
            typ, arg, _ = slot[0]
            if typ == "ptr":
                vals.append(f"{rn(arg)}.{'as_mut_ptr' if arg in outs else 'as_ptr'}() as usize")
            elif typ == "len":
                vals.append(f"{rn(arg)}.len()")
            elif typ in BITS:
                parts = [(f"(({rn(a)} as u32 & {hex((1 << BITS[t]) - 1)}) << {s})" if s
                          else f"({rn(a)} as u32 & {hex((1 << BITS[t]) - 1)})") for t, a, s in slot]
                vals.append("(" + " | ".join(parts) + ") as usize")
            else:
                vals.append(f"{rn(arg)} as usize")
        call = f"dsn_call{len(vals)}(DSN_SYS_{c['name'].upper()}{''.join(', ' + v for v in vals)})"
        rtype = {"i32": " -> i32", "u32": " -> u32", None: ""}[c["ret"]]
        body = (f"unsafe {{ {call} as u32 }}" if c["ret"] == "u32"
                else f"unsafe {{ {call} }}" if c["ret"] == "i32" else f"unsafe {{ {call}; }}")
        out += f"#[inline]\npub fn dsn_{c['name']}({', '.join(sig)}){rtype} {{ {body} }}\n"
    return out


def zig_module(calls):
    """App-side ecall wrappers for Zig (freestanding). @import this module."""
    out = NOTE + "// App-side wrappers for Zig apps (freestanding). `@import` this module.\n\n"
    for c in calls:
        out += f"pub const DSN_SYS_{c['name'].upper()}: usize = {c['num']};\n"
    out += "\n"
    for k in range(MAX_SLOTS + 1):
        params = "".join(f", a{i}: usize" for i in range(k))
        out += f"fn call{k}(n: usize{params}) i32 {{\n"
        out += '    return asm volatile ("ecall"\n        : [ret] "={a0}" (-> i32),\n        : [n] "{a7}" (n),\n'
        out += "".join(f'          [a{i}] "{{a{i}}}" (a{i}),\n' for i in range(k))
        out += "        : .{ .memory = true });\n}\n"
    out += "\n"
    rn = lambda s: s + "_" if s in ZIG_KW else s
    for c in calls:
        sig = []
        for typ, arg in c["params"]:
            sig.append(f"{rn(arg)}: []const u8" if typ in ("str", "buf")
                       else f"{rn(arg)}: []u8" if typ == "out"
                       else f"{rn(arg)}: u32" if typ == "u32" else f"{rn(arg)}: i32")
        ptype = {a: t for t, a in c["params"]}
        vals = []
        for slot in c["slots"]:
            typ, arg, _ = slot[0]
            if typ == "ptr":
                vals.append(f"@intFromPtr({rn(arg)}.ptr)")
            elif typ == "len":
                vals.append(f"{rn(arg)}.len")
            elif typ in BITS:
                parts = [(f"((@as(u32, @bitCast({rn(a)})) & {hex((1 << BITS[t]) - 1)}) << {s})" if s
                          else f"(@as(u32, @bitCast({rn(a)})) & {hex((1 << BITS[t]) - 1)})") for t, a, s in slot]
                vals.append(f"@as(usize, {' | '.join(parts)})")
            else:
                vals.append(f"@as(usize, {rn(arg)})" if ptype[arg] == "u32"
                            else f"@as(usize, @as(u32, @bitCast({rn(arg)})))")
        call = f"call{len(vals)}(DSN_SYS_{c['name'].upper()}{''.join(', ' + v for v in vals)})"
        rtype = {"i32": "i32", "u32": "u32", None: "void"}[c["ret"]]
        body = (f"return @as(u32, @bitCast({call}));" if c["ret"] == "u32"
                else f"return {call};" if c["ret"] == "i32" else f"_ = {call};")
        out += f"pub fn {c['name']}({', '.join(sig)}) {rtype} {{ {body} }}\n"
    return out


def dispatch(calls):
    out = NOTE
    for c in calls:
        out += f"case {c['num']}: {{ // {c['name']}\n"
        for i, slot in enumerate(c["slots"]):
            typ, arg, _ = slot[0]
            if typ == "ptr":
                is_str = any(t == "str" and a == arg for t, a in c["params"])
                if is_str:
                    out += (f"  char {arg}_buf[kStrMax + 1];\n"
                            f"  const char* {arg} = guestStr(vm, a[{i}], a[{i + 1}], {arg}_buf);\n")
                else:
                    is_out = any(t == "out" and a == arg for t, a in c["params"])
                    const = "" if is_out else "const "
                    out += (f"  const uint32_t {arg}_len = a[{i + 1}];\n"
                            f"  {const}uint8_t* {arg} = static_cast<{const}uint8_t*>(dvm_ptr(vm, a[{i}], {arg}_len));\n"
                            f"  (void){arg}_len;\n")
                    if is_out:
                        out += f"  const uint32_t {arg}_addr = a[{i}]; (void){arg}_addr;\n"
                out += f"  if (!{arg}) {{ a[0] = static_cast<uint32_t>(-1); break; }}\n"
            elif typ == "len":
                continue
            elif typ in BITS:
                for t, a_, s in slot:
                    cast = {"i16": "int16_t", "u16": "uint16_t", "u8": "uint8_t"}[t]
                    ctype = "int32_t" if t == "i16" else "uint32_t"
                    out += f"  const {ctype} {a_} = static_cast<{cast}>(a[{i}] >> {s}); (void){a_};\n"
            else:
                ctype = "int32_t" if typ == "i32" else "uint32_t"
                out += f"  const {ctype} {arg} = static_cast<{ctype}>(a[{i}]); (void){arg};\n"
        out += "  uint32_t result = 0;\n"
        out += f"  {c['stmt']}\n"
        out += "  a[0] = result;\n  break;\n}\n"
    return out


def main():
    calls = parse((ROOT / "abi/freeink.api").read_text())
    nums, wrappers = app_headers(calls)
    (ROOT / "sdk/dessen_sysnums.h").write_text(nums)
    (ROOT / "sdk/dessen_calls.h").write_text(wrappers)
    (ROOT / "freeink/dessen_dispatch.inc").write_text(dispatch(calls))
    (ROOT / "sdk/dessen.rs").write_text(rust_module(calls))
    (ROOT / "sdk/dessen.zig").write_text(zig_module(calls))
    print(f"generated {len(calls)} calls")


if __name__ == "__main__":
    main()
